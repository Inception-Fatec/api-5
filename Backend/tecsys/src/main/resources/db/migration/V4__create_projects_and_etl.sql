CREATE TABLE projects (
    id          BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    name        VARCHAR      NOT NULL,
    dist_code   VARCHAR(10)  NOT NULL,
    status      VARCHAR(20)  NOT NULL,
    created_by  BIGINT       NOT NULL,
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    active      BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT pk_projects PRIMARY KEY (id),
    CONSTRAINT fk_projects_created_by FOREIGN KEY (created_by) REFERENCES users (id)
);

CREATE TABLE project_coverage (
    project_id     BIGINT       NOT NULL,
    summary        JSONB        NOT NULL,
    gateways       JSONB        NOT NULL,
    points         JSONB        NOT NULL,
    calculated_at  TIMESTAMPTZ  NULL,
    CONSTRAINT pk_project_coverage PRIMARY KEY (project_id),
    CONSTRAINT fk_project_coverage_project FOREIGN KEY (project_id) REFERENCES projects (id)
);

CREATE TABLE project_history (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY,
    created_at     TIMESTAMPTZ  NULL,
    polygon        GEOMETRY     NULL,
    project_id     BIGINT       NOT NULL,
    filter_params  JSONB        NULL,
    CONSTRAINT pk_project_history PRIMARY KEY (id),
    CONSTRAINT fk_project_history_project FOREIGN KEY (project_id) REFERENCES projects (id)
);

CREATE TABLE etl_jobs (
    id                BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    status            VARCHAR(20)  NOT NULL,
    original_filename VARCHAR      NULL,
    municipios        VARCHAR      NOT NULL,
    summary_json      TEXT         NULL,
    log_tail          TEXT         NULL,
    error_message     TEXT         NULL,
    created_by        BIGINT       NULL,
    created_at        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    started_at        TIMESTAMPTZ  NULL,
    finished_at       TIMESTAMPTZ  NULL,
    CONSTRAINT pk_etl_jobs PRIMARY KEY (id),
    CONSTRAINT fk_etl_jobs_created_by FOREIGN KEY (created_by) REFERENCES users (id)
);